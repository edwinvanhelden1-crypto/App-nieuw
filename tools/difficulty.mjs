// Works out how hard each built-in drawing is to trace (number of shapes and
// path segments) and writes ar-tekenen/js/difficulty.js. Run after changing drawings:
//   node tools/difficulty.mjs
import { writeFileSync } from 'node:fs';
import { categories } from '../ar-tekenen/js/catalog.js';

const scores = {};
for (const c of categories) {
  for (const it of c.items) {
    const s = it.draw();
    const shapes = (s.match(/<(path|circle|ellipse|rect|text)\b/g) || []).length;
    const segments = (s.match(/[MLQCAHVZmlqcahvz]/g) || []).length;
    scores[it.id] = Math.round(shapes + segments / 6);
  }
}
const sorted = Object.values(scores).sort((a, b) => a - b);
const t1 = sorted[Math.floor(sorted.length / 3)], t2 = sorted[Math.floor((sorted.length * 2) / 3)];
const level = Object.fromEntries(Object.entries(scores).map(([id, v]) => [id, v <= t1 ? 1 : v <= t2 ? 2 : 3]));
writeFileSync(new URL('../ar-tekenen/js/difficulty.js', import.meta.url),
  '// Generated by tools/difficulty.mjs: 1 = makkelijk, 2 = gemiddeld, 3 = moeilijk; the number is the detail score.\n' +
  `export const scores = ${JSON.stringify(scores)};\nexport const levels = ${JSON.stringify(level)};\n`);
console.log('drempels', t1, t2, 'aantal', sorted.length);
